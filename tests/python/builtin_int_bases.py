# Partition fixtures because CloverVM code objects have 8-bit constant indices.
def check_cases(cases):
    # CloverVM loop targets do not support tuple unpacking yet.
    for case in cases:
        value = case[0]
        binary = case[1]
        octal = case[2]
        hexadecimal = case[3]
        for cls in (int, HostileInt):
            obj = cls(value)
            assert bin(obj) == binary
            assert oct(obj) == octal
            assert hex(obj) == hexadecimal
            assert bin(obj).__class__ is str
            assert oct(obj).__class__ is str
            assert hex(obj).__class__ is str

