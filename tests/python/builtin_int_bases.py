# Construct independent zero runs without unsupported string repetition.
def zeros(count):
    result = ""
    block = "0"
    while count > 0:
        if count & 1:
            result += block
        block += block
        count >>= 1
    return result

# Power-of-two formatting is independent of decimal conversion digit limits.
wide = 1 << 20000
assert bin(wide) == "0b1" + zeros(20000)
assert oct(wide) == "0o4" + zeros(6666)
assert hex(wide) == "0x1" + zeros(5000)
assert bin(-wide) == "-0b1" + zeros(20000)
assert oct(-wide) == "-0o4" + zeros(6666)
assert hex(-wide) == "-0x1" + zeros(5000)

assert bin(False) == "0b0"
assert bin(True) == "0b1"
assert oct(False) == "0o0"
assert oct(True) == "0o1"
assert hex(False) == "0x0"
assert hex(True) == "0x1"
assert builtins.bin is bin
assert builtins.oct is oct
assert builtins.hex is hex

class IntOnly:
    def __int__(self):
        raise AssertionError("unexpected conversion")

for fn in (bin, oct, hex):
    for value in (1.5, "12", b"12", None, [], IntOnly()):
        raised = False
        try:
            fn(value)
        except TypeError:
            raised = True
        assert raised
    raised = False
    try:
        fn()
    except TypeError:
        raised = True
    assert raised
    raised = False
    try:
        fn(1, 2)
    except TypeError:
        raised = True
    assert raised
    raised = False
    try:
        fn(number=1)
    except TypeError:
        raised = True
    assert raised
    raised = False
    try:
        fn(1, other=2)
    except TypeError:
        raised = True
    assert raised
